const fs = require('fs');
const vm = require('vm');
const path = require('path');
const root = path.resolve(__dirname, '..');
const ctx = JSON.parse(fs.readFileSync(path.join(root, 'veri/lineer-ctx.json'), 'utf8'));
ctx.num = function(v) { const m = String(v).replace(',', '.').match(/[\d.]+/); return m ? Number(m[0]) : NaN; };
const sandbox = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'lineer.js'), 'utf8'), sandbox);
const moduleDraw = sandbox.window.YDRAW.lineer;
if (!moduleDraw.match(ctx)) throw Error('Aile eşleşmedi');
const out = moduleDraw.draw(ctx, {id: 'hgh20ha', dim: '#0a2350'});
if (!out) throw Error('draw() null');
const expected = ['W', 'H', 'H1', 'N', 'B', 'C', 'L1', 'L', 'M'];
for (const k of expected) if (!out.keys.some(x => x.k === k)) throw Error('Eksik çizim anahtarı: ' + k);
fs.writeFileSync(path.join(root, 'onizleme/hgh20ha.svg'), out.svg);
fs.writeFileSync(path.join(root, 'veri/draw-keys.json'), JSON.stringify(out.keys, null, 2) + '\n');
console.log('draw() null değil; keys: ' + out.keys.map(x => x.k).join(', '));
const missing = {...ctx, specs: ctx.specs.filter(x => x.l !== 'H1'), onyazi: ctx.onyazi.filter(x => x.l !== 'H1')};
if (moduleDraw.draw(missing) !== null) throw Error('Eksik veri null dönmedi');
console.log('Eksik H1 kontrolü: null');
