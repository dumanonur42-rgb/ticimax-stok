-- Same rule as `normalize()` in the app: Turkish-aware uppercase, letters and digits only.
create or replace function public.norm_key(t text) returns text
language sql immutable as $$
  select regexp_replace(translate(upper(coalesce(t, '')), 'İIŞĞÜÖÇ', 'IISGUOC'), '[^A-Z0-9]+', '', 'g')
$$;
-- Fills the identity for writers that do not send it (older clients).
create or replace function public.products_fill_key() returns trigger
language plpgsql as $$
begin
  if new.key_norm is null or new.key_norm = '' then
    new.key_norm := new.sku_norm || '|' || norm_key(new.brand) || '|' || norm_key(new.box);
  end if;
  return new;
end $$;
drop trigger if exists products_fill_key on public.products;
create trigger products_fill_key before insert or update on public.products
  for each row execute function public.products_fill_key();
update public.products set key_norm = sku_norm || '|' || norm_key(brand) || '|' || norm_key(box) where key_norm = '';
alter table public.products drop constraint if exists products_sku_norm_key;
create index if not exists products_sku_norm on public.products (sku_norm);
create unique index if not exists products_key_norm on public.products (key_norm);

